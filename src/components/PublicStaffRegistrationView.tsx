import React, { useMemo, useState } from 'react';
import {
  UserPlus,
  IdCard,
  User,
  Phone,
  Building2,
  ShieldCheck,
  CheckCircle,
  Copy,
  Check,
  ArrowLeft,
  LogIn,
  Lock,
  Sparkles,
  FileText,
  AlertCircle,
  Clock
} from 'lucide-react';
import {
  Branch,
  DEFAULT_ROLE_PERMISSIONS,
  PtkpStatus,
  Staff,
  StaffRole,
  StaffTaxCategory,
  normalizeStaffRole
} from '../types';
import { PTKP_OPTIONS } from '../utils/taxService';
import {
  AVAILABLE_STAFF_ROLES,
  generateNextStaffId,
  resolveRoleDefaultPermissions
} from '../utils/staffRegistrationHelper';
import { getSavedPharmacyProfile } from './PharmacySettingsModal';

interface PublicStaffRegistrationViewProps {
  staffList: Staff[];
  branches: Branch[];
  rolePermissions?: Record<string, string[]>;
  isDemoSandbox?: boolean;
  onRegisterStaff: (newStaff: Staff) => Promise<Staff> | Staff;
  onBackToLogin: (prefillStaff?: Staff) => void;
}

export const PublicStaffRegistrationView: React.FC<PublicStaffRegistrationViewProps> = ({
  staffList,
  branches,
  rolePermissions = DEFAULT_ROLE_PERMISSIONS,
  isDemoSandbox = false,
  onRegisterStaff,
  onBackToLogin
}) => {
  const pharmacyProfile = useMemo(() => {
    try {
      return getSavedPharmacyProfile();
    } catch {
      return { name: 'APOTEK LATISHA FARMA', address: '', phone: '' };
    }
  }, []);

  const defaultBranchId = branches[0]?.id || 'BR-01';
  const autoGeneratedId = useMemo(() => generateNextStaffId(staffList), [staffList]);

  const [name, setName] = useState('');
  const [phone, setPhone] = useState('');
  const [branchId, setBranchId] = useState(defaultBranchId);
  const [npwpNik, setNpwpNik] = useState('');
  const [ptkpStatus, setPtkpStatus] = useState<PtkpStatus>('TK/0');
  const [taxCategory, setTaxCategory] = useState<StaffTaxCategory>('pegawai_tetap');
  const [selectedRole, setSelectedRole] = useState<StaffRole>('Apoteker');
  const [sipNumber, setSipNumber] = useState('');
  const [estrNumber, setEstrNumber] = useState('');
  const [sipbNumber, setSipbNumber] = useState('');
  const [isDpj, setIsDpj] = useState(false);

  const [errorMsg, setErrorMsg] = useState('');
  const [isSubmitting, setIsSubmitting] = useState(false);
  const [registeredStaff, setRegisteredStaff] = useState<Staff | null>(null);
  const [copiedId, setCopiedId] = useState(false);

  const isDoctorRole = selectedRole === 'Dokter';
  const isPharmacistRole = selectedRole === 'Apoteker';
  const isNurseOrMidwifeRole =
    selectedRole === 'Perawat / Bidan' || selectedRole === 'Perawat / Nakes Lapangan';

  const handleCopyStaffId = async (idToCopy: string) => {
    try {
      await navigator.clipboard?.writeText(idToCopy);
      setCopiedId(true);
      setTimeout(() => setCopiedId(false), 2200);
    } catch {}
  };

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    setErrorMsg('');

    const cleanName = name.trim();
    const cleanPhone = phone.trim();
    if (cleanName.length < 2) {
      setErrorMsg('Harap masukkan Nama Lengkap & Gelar pegawai minimal 2 karakter.');
      return;
    }
    if (cleanPhone.replace(/\D/g, '').length < 8) {
      setErrorMsg('Harap masukkan Nomor WhatsApp / Telepon pegawai yang valid.');
      return;
    }

    const normalizedName = cleanName.toLowerCase().replace(/\s+/g, ' ');
    const duplicateByName = staffList.find(
      (st) => String(st.name || '').trim().toLowerCase().replace(/\s+/g, ' ') === normalizedName
    );
    if (duplicateByName) {
      setErrorMsg(
        `Pegawai dengan nama "${duplicateByName.name}" sudah terdaftar dengan ID ${duplicateByName.id}. Gunakan ID tersebut untuk masuk ke sistem.`
      );
      return;
    }

    const finalRole = normalizeStaffRole(selectedRole, 'Apoteker');
    const assignedPerms = resolveRoleDefaultPermissions(finalRole, rolePermissions);
    const assignedId = generateNextStaffId(staffList);

    const payload: Staff = {
      id: assignedId,
      name: cleanName,
      phone: cleanPhone,
      role: finalRole,
      roles: [finalRole],
      permissions: assignedPerms,
      status: 'Menunggu Validasi',
      registeredAt: new Date().toISOString(),
      branchId: branchId || defaultBranchId,
      npwpNik: npwpNik.trim() || undefined,
      ptkpStatus,
      taxCategory,
      ...(finalRole === 'Dokter' || finalRole === 'Apoteker'
        ? {
            sipNumber: sipNumber.trim() || undefined,
            estrNumber: estrNumber.trim() || undefined
          }
        : {}),
      ...(finalRole === 'Dokter' ? { isDpj } : {}),
      ...(finalRole === 'Perawat / Bidan' || finalRole === 'Perawat / Nakes Lapangan'
        ? { sipbNumber: sipbNumber.trim() || undefined }
        : {})
    };

    setIsSubmitting(true);
    try {
      const saved = await onRegisterStaff(payload);
      setRegisteredStaff(saved || payload);
    } catch (err: any) {
      setErrorMsg(err?.message || 'Gagal menyimpan registrasi pegawai. Silakan coba lagi.');
    } finally {
      setIsSubmitting(false);
    }
  };

  const handleResetForm = () => {
    setRegisteredStaff(null);
    setName('');
    setPhone('');
    setBranchId(defaultBranchId);
    setNpwpNik('');
    setPtkpStatus('TK/0');
    setTaxCategory('pegawai_tetap');
    setSelectedRole('Apoteker');
    setSipNumber('');
    setEstrNumber('');
    setSipbNumber('');
    setIsDpj(false);
    setErrorMsg('');
  };

  return (
    <div className="min-h-screen bg-slate-950 text-slate-800 overflow-y-auto py-4 px-3 sm:py-8 sm:px-6">
      <div className="max-w-4xl mx-auto space-y-4">
        {/* Top Navigation Bar */}
        <div className="flex flex-wrap items-center justify-between gap-3">
          <button
            type="button"
            onClick={() => onBackToLogin(registeredStaff || undefined)}
            className="inline-flex items-center gap-2 px-3.5 py-2 rounded-xl bg-slate-900 hover:bg-slate-800 text-slate-200 border border-slate-700 text-xs font-bold transition cursor-pointer"
          >
            <ArrowLeft className="w-4 h-4 text-sky-400" />
            <span>Kembali ke Login Pegawai</span>
          </button>

          {isDemoSandbox && (
            <span className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-xl bg-amber-400 text-slate-950 text-[11px] font-black uppercase tracking-wide">
              <Sparkles className="w-3.5 h-3.5" /> Mode Demo Sandbox
            </span>
          )}
        </div>

        {/* Main Card */}
        <div className="bg-white rounded-2xl sm:rounded-3xl shadow-2xl border border-slate-800 overflow-hidden">
          {/* Header */}
          <div className="px-5 py-5 sm:px-7 bg-slate-900 text-white border-b border-slate-800 flex flex-col sm:flex-row sm:items-center justify-between gap-4">
            <div className="flex items-center gap-3.5">
              <div className="w-12 h-12 sm:w-14 sm:h-14 bg-white p-1.5 rounded-2xl flex items-center justify-center shadow-lg shrink-0 overflow-hidden">
                <img
                  src={`${import.meta.env.BASE_URL}assets/aistudio/logo_resmi_apotek_673c56f0.png`}
                  alt="Logo Apotek Latisha Farma"
                  className="w-full h-full object-contain"
                />
              </div>
              <div>
                <div className="inline-flex items-center gap-1.5 px-2 py-0.5 rounded-full bg-violet-500/20 text-violet-300 border border-violet-400/30 text-[10px] font-extrabold uppercase tracking-wider mb-1">
                  <UserPlus className="w-3 h-3" />
                  <span>Registrasi Akun Pegawai Mandiri</span>
                </div>
                <h1 className="text-base sm:text-xl font-black tracking-tight text-white">
                  {pharmacyProfile?.name || 'LATISHA FARMA'}
                </h1>
                <p className="text-[11px] text-slate-300 mt-0.5">
                  Pendaftaran akun petugas dengan ID Pegawai otomatis &amp; sinkronisasi peran hak akses
                </p>
              </div>
            </div>

            <div className="px-3.5 py-2.5 rounded-2xl bg-slate-800/90 border border-slate-700 text-left sm:text-right shrink-0">
              <span className="block text-[10px] uppercase tracking-wider text-slate-400 font-bold">
                ID Pegawai Anda Berikutnya
              </span>
              <span className="font-mono font-black text-base text-sky-400 tracking-wider">
                {registeredStaff ? registeredStaff.id : autoGeneratedId}
              </span>
            </div>
          </div>

          {/* Content Body */}
          {registeredStaff ? (
            <div className="p-5 sm:p-8 space-y-6 text-xs">
              <div
                className={`p-4 sm:p-5 rounded-2xl border-2 flex flex-col sm:flex-row sm:items-center justify-between gap-4 ${
                  registeredStaff.status === 'Menunggu Validasi'
                    ? 'bg-amber-50 border-amber-300'
                    : 'bg-emerald-50 border-emerald-300'
                }`}
              >
                <div className="flex items-start gap-3">
                  <div
                    className={`w-10 h-10 rounded-xl text-white flex items-center justify-center shrink-0 ${
                      registeredStaff.status === 'Menunggu Validasi'
                        ? 'bg-amber-600'
                        : 'bg-emerald-600'
                    }`}
                  >
                    {registeredStaff.status === 'Menunggu Validasi' ? (
                      <Clock className="w-6 h-6" />
                    ) : (
                      <CheckCircle className="w-6 h-6" />
                    )}
                  </div>
                  <div>
                    <h2
                      className={`text-sm sm:text-base font-black ${
                        registeredStaff.status === 'Menunggu Validasi'
                          ? 'text-amber-950'
                          : 'text-emerald-950'
                      }`}
                    >
                      {registeredStaff.status === 'Menunggu Validasi'
                        ? 'Pendaftaran Terkirim — Menunggu Validasi APJ / Owner'
                        : 'Registrasi Akun Pegawai Berhasil!'}
                    </h2>
                    <p
                      className={`text-[11px] mt-0.5 leading-relaxed ${
                        registeredStaff.status === 'Menunggu Validasi'
                          ? 'text-amber-900'
                          : 'text-emerald-800'
                      }`}
                    >
                      {registeredStaff.status === 'Menunggu Validasi' ? (
                        <>
                          Data pendaftaran Anda telah dikirim ke notifikasi akun{' '}
                          <strong>APJ / Owner</strong> untuk divalidasi terlebih dahulu. Setelah
                          divalidasi oleh APJ / Owner, Anda sudah dapat langsung masuk (login) ke
                          sistem aplikasi menggunakan Nama dan ID Pegawai Anda.
                        </>
                      ) : (
                        <>
                          Data Anda telah otomatis tersimpan ke menu{' '}
                          <strong>Pengaturan → Peran User (Pegawai)</strong> beserta checkbox peran
                          dan hak akses modul sesuai jabatan yang dipilih.
                        </>
                      )}
                    </p>
                  </div>
                </div>
                <span
                  className={`px-3 py-1 rounded-full text-white font-extrabold text-[11px] shrink-0 self-start sm:self-center ${
                    registeredStaff.status === 'Menunggu Validasi'
                      ? 'bg-amber-600'
                      : 'bg-emerald-600'
                  }`}
                >
                  Status: {registeredStaff.status}
                </span>
              </div>

              {/* Employee ID & Account Card */}
              <div className="grid grid-cols-1 md:grid-cols-12 gap-4">
                <div className="md:col-span-5 p-4 rounded-2xl bg-sky-50 border-2 border-sky-300 space-y-3">
                  <div>
                    <span className="text-[10px] font-extrabold uppercase tracking-wider text-sky-700 block">
                      ID Pegawai Resmi Anda (Untuk Login)
                    </span>
                    <div className="mt-1.5 flex items-center justify-between gap-2 bg-white px-3.5 py-2.5 rounded-xl border border-sky-200">
                      <span className="font-mono font-black text-xl text-sky-900 tracking-wider">
                        {registeredStaff.id}
                      </span>
                      <button
                        type="button"
                        onClick={() => handleCopyStaffId(registeredStaff.id)}
                        className="inline-flex items-center gap-1 px-2.5 py-1.5 rounded-lg bg-sky-600 hover:bg-sky-700 text-white font-bold text-[11px] cursor-pointer transition"
                      >
                        {copiedId ? (
                          <>
                            <Check className="w-3.5 h-3.5" />
                            <span>Tersalin</span>
                          </>
                        ) : (
                          <>
                            <Copy className="w-3.5 h-3.5" />
                            <span>Salin ID</span>
                          </>
                        )}
                      </button>
                    </div>
                  </div>
                  <p className="text-[11px] text-sky-900 leading-snug">
                    Catat atau salin <strong>ID Pegawai</strong> di atas. Gunakan{' '}
                    <strong>Nama Petugas</strong> dan <strong>ID Pegawai</strong> tersebut saat
                    masuk ke sistem.
                  </p>
                </div>

                <div className="md:col-span-7 p-4 rounded-2xl bg-slate-50 border border-slate-200 grid grid-cols-1 sm:grid-cols-2 gap-3">
                  <div>
                    <span className="text-[10px] font-bold uppercase text-slate-400 block">
                      Nama Pegawai &amp; Gelar
                    </span>
                    <span className="font-extrabold text-slate-900 text-xs mt-0.5 block">
                      {registeredStaff.name}
                    </span>
                  </div>
                  <div>
                    <span className="text-[10px] font-bold uppercase text-slate-400 block">
                      Role / Jabatan Aktif
                    </span>
                    <span className="inline-flex items-center gap-1 font-extrabold text-violet-800 bg-violet-100 px-2.5 py-0.5 rounded-lg border border-violet-200 text-xs mt-0.5">
                      <ShieldCheck className="w-3.5 h-3.5" />
                      {registeredStaff.role}
                    </span>
                  </div>
                  <div>
                    <span className="text-[10px] font-bold uppercase text-slate-400 block">
                      No. WhatsApp / Telepon
                    </span>
                    <span className="font-mono font-bold text-slate-800 mt-0.5 block">
                      {registeredStaff.phone}
                    </span>
                  </div>
                  <div>
                    <span className="text-[10px] font-bold uppercase text-slate-400 block">
                      Penempatan Cabang
                    </span>
                    <span className="font-bold text-slate-800 mt-0.5 block">
                      {branches.find((b) => b.id === registeredStaff.branchId)?.name ||
                        registeredStaff.branchId}
                    </span>
                  </div>
                  <div>
                    <span className="text-[10px] font-bold uppercase text-slate-400 block">
                      NPWP / NIK (PPh 21)
                    </span>
                    <span className="font-mono text-slate-700 mt-0.5 block">
                      {registeredStaff.npwpNik || '-'}
                    </span>
                  </div>
                  <div>
                    <span className="text-[10px] font-bold uppercase text-slate-400 block">
                      Status PTKP &amp; Kategori Pajak
                    </span>
                    <span className="font-bold text-slate-700 mt-0.5 block">
                      {registeredStaff.ptkpStatus || 'TK/0'} ·{' '}
                      {registeredStaff.taxCategory === 'bukan_pegawai'
                        ? 'Bukan Pegawai / Nakes'
                        : 'Pegawai Tetap'}
                    </span>
                  </div>
                  {(registeredStaff.role === 'Dokter' || registeredStaff.role === 'Apoteker') && (
                    <>
                      <div>
                        <span className="text-[10px] font-bold uppercase text-slate-400 block">
                          {registeredStaff.role === 'Dokter' ? 'No. SIP Dokter' : 'No. SIP / SIPA Apoteker'}
                        </span>
                        <span className="font-mono font-bold text-slate-800 mt-0.5 block">
                          {registeredStaff.sipNumber || '-'}
                        </span>
                      </div>
                      <div>
                        <span className="text-[10px] font-bold uppercase text-slate-400 block">
                          No. E-STR
                        </span>
                        <span className="font-mono font-bold text-slate-800 mt-0.5 block">
                          {registeredStaff.estrNumber || '-'}
                        </span>
                      </div>
                    </>
                  )}
                  {(registeredStaff.role === 'Perawat / Bidan' ||
                    registeredStaff.role === 'Perawat / Nakes Lapangan') && (
                    <div className="sm:col-span-2">
                      <span className="text-[10px] font-bold uppercase text-slate-400 block">
                        No. SIPB / E-STR
                      </span>
                      <span className="font-mono font-bold text-slate-800 mt-0.5 block">
                        {registeredStaff.sipbNumber || '-'}
                      </span>
                    </div>
                  )}
                  {registeredStaff.role === 'Dokter' && (
                    <div className="sm:col-span-2">
                      <span className="text-[10px] font-bold uppercase text-slate-400 block">
                        Status Dokter Penanggung Jawab (DPJ)
                      </span>
                      <span
                        className={`inline-flex items-center gap-1 mt-0.5 px-2.5 py-0.5 rounded-lg font-bold text-[11px] border ${
                          registeredStaff.isDpj
                            ? 'bg-emerald-100 text-emerald-900 border-emerald-300'
                            : 'bg-slate-100 text-slate-600 border-slate-200'
                        }`}
                      >
                        {registeredStaff.isDpj
                          ? 'Terdaftar sebagai Dokter Penanggung Jawab (Data otomatis tersimpan ke Profil DPJ)'
                          : 'Dokter Praktik Reguler (Tidak diset sebagai DPJ)'}
                      </span>
                    </div>
                  )}
                </div>
              </div>

              <div className="flex flex-col sm:flex-row items-stretch sm:items-center justify-end gap-2.5 pt-2">
                <button
                  type="button"
                  onClick={handleResetForm}
                  className="px-4 py-2.5 rounded-xl border border-slate-300 bg-white hover:bg-slate-50 text-slate-700 font-bold text-xs cursor-pointer transition"
                >
                  Daftarkan Pegawai Lain
                </button>
                <button
                  type="button"
                  onClick={() => onBackToLogin(registeredStaff)}
                  className="px-5 py-2.5 rounded-xl bg-sky-600 hover:bg-sky-700 text-white font-black text-xs flex items-center justify-center gap-2 shadow-lg cursor-pointer transition"
                >
                  <LogIn className="w-4 h-4" />
                  <span>
                    {registeredStaff.status === 'Menunggu Validasi'
                      ? 'Kembali ke Halaman Login'
                      : 'Masuk / Login dengan Akun Ini'}
                  </span>
                </button>
              </div>
            </div>
          ) : (
            <form onSubmit={handleSubmit} className="p-5 sm:p-7 space-y-5 text-xs">
              {errorMsg && (
                <div className="p-3.5 rounded-2xl bg-rose-50 border border-rose-300 text-rose-800 flex items-start gap-2.5">
                  <AlertCircle className="w-4 h-4 text-rose-600 shrink-0 mt-0.5" />
                  <div>
                    <strong className="font-bold block">Registrasi Belum Dapat Diproses</strong>
                    <span>{errorMsg}</span>
                  </div>
                </div>
              )}

              {/* Row 1: ID Pegawai Otomatis & Role Dropdown */}
              <div className="grid grid-cols-1 sm:grid-cols-2 gap-3.5 p-4 rounded-2xl bg-sky-50/60 border border-sky-200">
                <div>
                  <div className="flex items-center justify-between gap-1 mb-1">
                    <label className="block text-[10px] font-extrabold text-sky-900 uppercase">
                      ID Pegawai (Terisi Otomatis)
                    </label>
                    <span className="inline-flex items-center gap-1 text-[10px] font-bold text-sky-700 bg-white px-2 py-0.5 rounded border border-sky-200">
                      <Lock className="w-2.5 h-2.5" /> Otomatis
                    </span>
                  </div>
                  <div className="relative flex items-center gap-2">
                    <div className="relative flex-1">
                      <input
                        type="text"
                        value={autoGeneratedId}
                        readOnly
                        className="w-full min-h-[42px] py-2 pr-3 pl-9 border-2 border-sky-300 rounded-xl font-mono font-black text-sky-900 bg-white select-all outline-none"
                      />
                      <IdCard className="w-4 h-4 text-sky-600 absolute left-3 top-1/2 -translate-y-1/2" />
                    </div>
                    <button
                      type="button"
                      onClick={() => handleCopyStaffId(autoGeneratedId)}
                      className="min-h-[42px] px-3 rounded-xl bg-white hover:bg-sky-100 border border-sky-300 text-sky-800 font-bold text-[11px] flex items-center gap-1 shrink-0 cursor-pointer transition"
                      title="Salin ID Pegawai"
                    >
                      {copiedId ? (
                        <Check className="w-3.5 h-3.5 text-emerald-600" />
                      ) : (
                        <Copy className="w-3.5 h-3.5" />
                      )}
                      <span>{copiedId ? 'Disalin' : 'Salin'}</span>
                    </button>
                  </div>
                  <p className="text-[10px] text-sky-800 mt-1">
                    Simpan ID <strong>{autoGeneratedId}</strong> ini untuk masuk (login) ke sistem.
                  </p>
                </div>

                <div>
                  <label className="block text-[10px] font-extrabold text-slate-700 uppercase mb-1">
                    Pilih Role / Peran Pegawai *
                  </label>
                  <div className="relative">
                    <select
                      value={selectedRole}
                      onChange={(e) => {
                        const nextRole = e.target.value as StaffRole;
                        setSelectedRole(nextRole);
                        if (nextRole !== 'Dokter') {
                          setIsDpj(false);
                        }
                      }}
                      required
                      className="w-full min-h-[42px] py-2 pr-3 pl-9 border-2 border-violet-300 rounded-xl font-extrabold text-slate-900 bg-white focus:ring-2 focus:ring-violet-500 outline-none cursor-pointer"
                    >
                      {AVAILABLE_STAFF_ROLES.map((r) => (
                        <option key={r} value={r}>
                          {r}
                        </option>
                      ))}
                    </select>
                    <ShieldCheck className="w-4 h-4 text-violet-600 absolute left-3 top-1/2 -translate-y-1/2 pointer-events-none" />
                  </div>
                  <p className="text-[10px] text-slate-500 mt-1">
                    Hak akses modul otomatis tercentang sesuai peran yang diatur dalam sistem.
                  </p>
                </div>
              </div>

              {/* Row 2: Nama Pegawai, No WA, Cabang (Identical to + User Baru Pegawai) */}
              <div className="grid grid-cols-1 sm:grid-cols-3 gap-3">
                <div>
                  <label className="block text-[10px] font-bold text-slate-600 uppercase mb-1">
                    Nama Pegawai &amp; Gelar *
                  </label>
                  <div className="relative">
                    <input
                      type="text"
                      required
                      placeholder="Contoh: apt. Budi Santoso, S.Farm"
                      value={name}
                      onChange={(e) => {
                        setName(e.target.value);
                        if (errorMsg) setErrorMsg('');
                      }}
                      className="w-full min-h-[42px] py-2 pr-3 pl-9 border border-slate-300 rounded-xl font-bold bg-white focus:ring-2 focus:ring-sky-500 outline-none"
                    />
                    <User className="w-4 h-4 text-slate-400 absolute left-3 top-1/2 -translate-y-1/2" />
                  </div>
                </div>
                <div>
                  <label className="block text-[10px] font-bold text-slate-600 uppercase mb-1">
                    No. WhatsApp / Telepon *
                  </label>
                  <div className="relative">
                    <input
                      type="text"
                      required
                      placeholder="0812-..."
                      value={phone}
                      onChange={(e) => {
                        setPhone(e.target.value);
                        if (errorMsg) setErrorMsg('');
                      }}
                      className="w-full min-h-[42px] py-2 pr-3 pl-9 border border-slate-300 rounded-xl font-mono font-bold bg-white focus:ring-2 focus:ring-sky-500 outline-none"
                    />
                    <Phone className="w-4 h-4 text-slate-400 absolute left-3 top-1/2 -translate-y-1/2" />
                  </div>
                </div>
                <div>
                  <label className="block text-[10px] font-bold text-slate-600 uppercase mb-1">
                    Penempatan Cabang
                  </label>
                  <div className="relative">
                    <select
                      value={branchId}
                      onChange={(e) => setBranchId(e.target.value)}
                      className="w-full min-h-[42px] py-2 pr-3 pl-9 border border-slate-300 rounded-xl font-bold bg-white focus:ring-2 focus:ring-sky-500 outline-none cursor-pointer"
                    >
                      {branches.map((b) => (
                        <option key={b.id} value={b.id}>
                          {b.name}
                        </option>
                      ))}
                    </select>
                    <Building2 className="w-4 h-4 text-slate-400 absolute left-3 top-1/2 -translate-y-1/2 pointer-events-none" />
                  </div>
                </div>
              </div>

              {/* Row 3: NPWP / NIK, PTKP, Kategori PPh 21 (Identical to + User Baru Pegawai) */}
              <div className="grid grid-cols-1 sm:grid-cols-3 gap-3">
                <div>
                  <label className="block text-[10px] font-bold text-slate-600 uppercase mb-1">
                    NPWP / NIK (PPh 21)
                  </label>
                  <div className="relative">
                    <input
                      type="text"
                      placeholder="16 digit NIK atau NPWP"
                      value={npwpNik}
                      onChange={(e) => setNpwpNik(e.target.value)}
                      className="w-full min-h-[42px] py-2 pr-3 pl-9 border border-slate-300 rounded-xl font-mono text-xs bg-white focus:ring-2 focus:ring-sky-500 outline-none"
                    />
                    <FileText className="w-4 h-4 text-slate-400 absolute left-3 top-1/2 -translate-y-1/2" />
                  </div>
                </div>
                <div>
                  <label className="block text-[10px] font-bold text-slate-600 uppercase mb-1">
                    Status PTKP
                  </label>
                  <select
                    value={ptkpStatus}
                    onChange={(e) => setPtkpStatus(e.target.value as PtkpStatus)}
                    className="w-full min-h-[42px] px-3 py-2 border border-slate-300 rounded-xl font-bold text-xs bg-white focus:ring-2 focus:ring-sky-500 outline-none cursor-pointer"
                  >
                    {PTKP_OPTIONS.map((opt) => (
                      <option key={opt.value} value={opt.value}>
                        {opt.value} (Kat. TER {opt.terCategory})
                      </option>
                    ))}
                  </select>
                </div>
                <div>
                  <label className="block text-[10px] font-bold text-slate-600 uppercase mb-1">
                    Kategori Penerima PPh 21
                  </label>
                  <select
                    value={taxCategory}
                    onChange={(e) => setTaxCategory(e.target.value as StaffTaxCategory)}
                    className="w-full min-h-[42px] px-3 py-2 border border-slate-300 rounded-xl font-bold text-xs bg-white focus:ring-2 focus:ring-sky-500 outline-none cursor-pointer"
                  >
                    <option value="pegawai_tetap">Pegawai Tetap (Skema TER)</option>
                    <option value="bukan_pegawai">Bukan Pegawai / Nakes (DPP 50%)</option>
                  </select>
                </div>
              </div>

              {/* Conditional Licensing Columns per Role */}
              {(isDoctorRole || isPharmacistRole) && (
                <div className="p-4 rounded-2xl bg-emerald-50/60 border border-emerald-200 space-y-3">
                  <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
                    <div>
                      <label className="block text-[10px] font-extrabold text-emerald-950 uppercase mb-1">
                        {isDoctorRole ? 'No. SIP Dokter' : 'No. SIP / SIPA Apoteker'}
                      </label>
                      <input
                        type="text"
                        placeholder={isDoctorRole ? 'Contoh: SIP/2025/001-KNA' : 'Contoh: 1993/SIPA/MSJ/2025'}
                        value={sipNumber}
                        onChange={(e) => setSipNumber(e.target.value)}
                        className="w-full min-h-[42px] px-3 py-2 border border-emerald-300 rounded-xl font-mono text-xs font-bold bg-white focus:ring-2 focus:ring-emerald-500 outline-none"
                      />
                    </div>
                    <div>
                      <label className="block text-[10px] font-extrabold text-emerald-950 uppercase mb-1">
                        {isDoctorRole ? 'No. E-STR Dokter' : 'No. E-STR Apoteker'}
                      </label>
                      <input
                        type="text"
                        placeholder="Masukkan Nomor E-STR"
                        value={estrNumber}
                        onChange={(e) => setEstrNumber(e.target.value)}
                        className="w-full min-h-[42px] px-3 py-2 border border-emerald-300 rounded-xl font-mono text-xs font-bold bg-white focus:ring-2 focus:ring-emerald-500 outline-none"
                      />
                    </div>
                  </div>

                  {isDoctorRole && (
                    <label className="flex items-start gap-2.5 p-3 rounded-xl bg-white border border-emerald-300 cursor-pointer select-none hover:bg-emerald-50/40 transition">
                      <input
                        type="checkbox"
                        checked={isDpj}
                        onChange={(e) => setIsDpj(e.target.checked)}
                        className="w-4 h-4 mt-0.5 accent-emerald-600 rounded cursor-pointer"
                      />
                      <div>
                        <span className="block font-extrabold text-emerald-950 text-xs">
                          Dokter Penanggung Jawab (DPJ)
                        </span>
                        <span className="block text-[11px] text-slate-600 mt-0.5">
                          Jika dicentang, data nama dokter, No. SIP, No. E-STR, dan kontak otomatis tersimpan ke data <strong>Profil DPJ</strong> pada sistem.
                        </span>
                      </div>
                    </label>
                  )}
                </div>
              )}

              {isNurseOrMidwifeRole && (
                <div className="p-4 rounded-2xl bg-sky-50/60 border border-sky-200">
                  <label className="block text-[10px] font-extrabold text-sky-950 uppercase mb-1">
                    No. SIPB / E-STR
                  </label>
                  <input
                    type="text"
                    placeholder="Masukkan Nomor SIPB atau E-STR Bidan / Perawat"
                    value={sipbNumber}
                    onChange={(e) => setSipbNumber(e.target.value)}
                    className="w-full min-h-[42px] px-3 py-2 border border-sky-300 rounded-xl font-mono text-xs font-bold bg-white focus:ring-2 focus:ring-sky-500 outline-none"
                  />
                </div>
              )}

              <div className="flex flex-col-reverse sm:flex-row sm:items-center justify-between gap-3 pt-1">
                <p className="text-[11px] text-slate-500">
                  Setelah mendaftar, notifikasi otomatis dikirim ke{' '}
                  <strong>APJ / Owner</strong> untuk validasi akun sebelum login ke sistem.
                </p>
                <button
                  type="submit"
                  disabled={isSubmitting}
                  className="min-h-[46px] px-6 py-3 bg-violet-700 hover:bg-violet-800 disabled:opacity-50 text-white font-black rounded-xl text-xs uppercase tracking-wider flex items-center justify-center gap-2 shadow-lg cursor-pointer transition"
                >
                  <UserPlus className="w-4 h-4" />
                  <span>{isSubmitting ? 'Menyimpan...' : 'Daftar Akun Pegawai Sekarang'}</span>
                </button>
              </div>
            </form>
          )}
        </div>
      </div>
    </div>
  );
};
